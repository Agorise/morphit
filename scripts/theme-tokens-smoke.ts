let failed = 0;
let passed = 0;
function check(name: string, ok: boolean, detail = ''): void {
	if (ok) {
		console.log(`  ✓ ${name}`);
		passed++;
	} else {
		console.error(`  ✗ ${name}${detail ? `\n      ${detail}` : ''}`);
		failed++;
	}
}

/** `--x-rgb: R G B` declarations of the FIRST `:root {…}` block in a CSS text. */
function rootRgbVars(css: string): Map<string, string> {
	const out = new Map<string, string>();
	const noComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
	const m = /:root\s*\{([^}]*)\}/.exec(noComments);
	if (!m) return out;
	for (const d of m[1]!.matchAll(/(--[a-z0-9-]+-rgb)\s*:\s*([^;]+);?/g))
		out.set(d[1]!, d[2]!.trim());
	return out;
}

