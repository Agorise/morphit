#!/usr/bin/env tsx
/**
 * scripts/theme-tokens-smoke.ts — per-instance colour theming: the DEFAULT
 * theme must stay exactly the Morphit look (docs/BRANDING.md, "Colours").
 *
 * The colour values live in several places that must agree, and a drift in any
 * of them silently re-colours every unthemed instance (or makes a theme miss a
 * surface):
 *   TT-1  apps/web/src/theme.css (the ONE file the compiled CSS reads colours
 *         from) defines exactly the THEME_TOKENS of
 *         packages/operator-config/src/theme.ts, each with its Morphit value.
 *   TT-2  deriveTheme(Morphit preset) reproduces those values exactly (so
 *         `branding apply --theme morphit` / no theme = canonical bytes).
 *   TT-3  tailwind.config.js maps its colours only to defined tokens.
 *   TT-4  The theme-color slot: src/app.html's meta, build-brand-slots.mjs's
 *         CANONICAL_THEME_COLOR and the token brand-2 agree.
 *   TT-5  static/manifest.webmanifest's theme/background colours are the
 *         brand-2 / surface-page tokens (branding rewrites them from a theme).
 *   TT-6  Icons generated by branding sit on the surface-page canvas by default.
 *   TT-7  The theme <style> id is the same in ops-cli's writer and the web's
 *         reader (applyTheme leaves a server-themed page alone by that id).
 *   TT-8  When a built frontend is present (apps/web/build), its COMPILED CSS
 *         :root carries exactly the Morphit token values.
 *   TT-9  The 1px edge a primary button lights on hover stands out from the
 *         button's face (1.8:1, as painted: at the rule's own opacity) in every
 *         preset (deep and bright buttons), on white and near-white bright
 *         buttons, and in 200 random themes — read from the CSS rules (source,
 *         and the build when present), so an edge painted in the face's own
 *         colour fails here.
 *   TT-10 /brand/theme.css (every page links it before it paints) sets nothing
 *         canonically, and app.html (and the built shell) link it as a plain,
 *         render-blocking stylesheet ahead of the app's head.
 *
 * The full pixel-level proof (screenshots of a build before/after, plus a
 * compiled-rule equivalence check) is apps/web/scripts/theme-pixel-check.mjs —
 * too heavy for the battery (needs Chromium); see its header.
 */
